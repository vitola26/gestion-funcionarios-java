    private void CargarTabla() {
        String[] columnas = {"ID", "Cedula", "Nombre", "Apellido", "Email", "Telefono", "Fecha Ingreso"};
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(columnas, 0);
        try {
            for (modelo.Funcionario f : dao.listarTodos()) {
                modelo.addRow(new Object[]{
                    f.getId(), f.getCedula(), f.getNombre(), f.getApellido(),
                    f.getEmail(), f.getTelefono(), f.getFechaIngreso()});
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar: " + e.getMessage());
        }
        tablaDatos.setModel(modelo);
    }
    
    // Obtiene el ID del funcionario seleccionado en la tabla
    private int getIdSeleccionado() {
        int fila = tablaDatos.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un funcionario de la tabla.");
            return -1;
        }
        return (int) tablaDatos.getValueAt(fila, 0);
    }
    
    
    

