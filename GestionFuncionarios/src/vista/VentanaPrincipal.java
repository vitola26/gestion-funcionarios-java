    private void btnNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevoActionPerformed

        // Pedimos los datos con cuadros de diálogo simples
        String cedula = javax.swing.JOptionPane.showInputDialog(this, "Cedula:");
        if (cedula == null || cedula.isEmpty()) return;
        
        String nombre = javax.swing.JOptionPane.showInputDialog(this, "Nombre:");
        String apellido = javax.swing.JOptionPane.showInputDialog(this, "Apellido:");
        String email = javax.swing.JOptionPane.showInputDialog(this, "Email:");
        String telefono = javax.swing.JOptionPane.showInputDialog(this, "Telefono:");
        String fecha = javax.swing.JOptionPane.showInputDialog(this, "Fecha de ingreso (YYYY-MM-DD):");
        
        modelo.Funcionario f = new modelo.Funcionario();
        f.setCedula(cedula); 
        f.setNombre(nombre);
        f.setApellido(apellido);
        f.setEmail(email); 
        f.setTelefono(telefono);
        f.setFechaIngreso(fecha);
        
        try {
            dao.crear(f);
            javax.swing.JOptionPane.showMessageDialog(this, "Funcionario creado.");
            CargarTabla();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    
    }//GEN-LAST:event_btnNuevoActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
    
        int id = getIdSeleccionado();
        if (id == -1) return;
        
        int fila = tablaDatos.getSelectedRow();
        
        // Prellenamos con los valores actuales de la fila seleccionada
        String cedula = javax.swing.JOptionPane.showInputDialog(this, "Cedula:", tablaDatos.getValueAt(fila, 1));
        if (cedula == null) return;
        
        String nombre = javax.swing.JOptionPane.showInputDialog(this, "Nombre:", tablaDatos.getValueAt(fila, 2));
        String apellido = javax.swing.JOptionPane.showInputDialog(this, "Apellido:", tablaDatos.getValueAt(fila, 3));
        String email = javax.swing.JOptionPane.showInputDialog(this, "Email:", tablaDatos.getValueAt(fila, 4));
        String telefono = javax.swing.JOptionPane.showInputDialog(this, "Telefono:", tablaDatos.getValueAt(fila, 5));
        String fecha = javax.swing.JOptionPane.showInputDialog(this, "Fecha (YYYY-MM-DD):", tablaDatos.getValueAt(fila, 6));
        
        modelo.Funcionario f = new modelo.Funcionario();
        f.setId(id); 
        f.setCedula(cedula);
        f.setNombre(nombre);
        f.setApellido(apellido); 
        f.setEmail(email);
        f.setTelefono(telefono);
        f.setFechaIngreso(fecha);
        
        try {
            dao.actualizar(f);
            javax.swing.JOptionPane.showMessageDialog(this, "Funcionario actualizado.");
            CargarTabla();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       
        int id = getIdSeleccionado();
        if (id == -1) return;
        
        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Eliminar este funcionario?", 
            "Confirmar", 
            javax.swing.JOptionPane.YES_NO_OPTION
        );
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            try {
                dao.eliminar(id);
                javax.swing.JOptionPane.showMessageDialog(this, "Funcionario eliminado.");
                CargarTabla();
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

